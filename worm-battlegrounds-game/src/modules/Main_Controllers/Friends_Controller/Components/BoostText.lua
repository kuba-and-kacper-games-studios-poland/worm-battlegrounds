--- @class Friends_Controller_BoostText : Component
--- @field Instance TextLabel
--- @field Connections { [string]: RBXScriptConnection }
--- @field _destroyed boolean
local Component = {}
Component.__index = Component

--%%%%%%%%%%%%%%%%%%%% New Class

function Component.new(instance: Instance)
	return setmetatable({ Instance = instance, Connections = {}, _destroyed = false }, Component)
end

--%%%%%%%%%%%%%%%%%%%% Init

function Component:Init()
	--[[ Connecting ]]

	table.insert(
		self.Connections,
		I.Topic.Subscribe("Friends_Controller_BoostChanged", function(boostText: string)
			self.Instance.Text = boostText
		end)
	)

	--[[ Applying ]]

	self.Instance.Text = I.Friends_Controller.GetBoostText()
end

--%%%%%%%%%%%%%%%%%%%% Destroy

function Component:Destroy()
	-- Disconnect All Connections
	for _, connection in ipairs(self.Connections) do
		connection:Disconnect()
	end
end

return Component
